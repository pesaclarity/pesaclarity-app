"""Writes lib/src/core/money/currency_data.dart from Unicode CLDR data.

Run with Babel installed (pip install babel==2.16.0):

    python tool/currencies.py

Lists every currency that is legal tender somewhere today, with its English
name and minor-unit digits, and each territory's currency, so the app can
suggest the currency of the phone's region anywhere.
"""

import datetime
import pathlib

from babel import Locale
from babel.numbers import get_currency_name, get_currency_precision, get_territory_currencies

today = datetime.date.today()
english = Locale("en")

by_territory = {}
for territory in sorted(english.territories):
    if len(territory) != 2 or not territory.isalpha():
        continue
    codes = get_territory_currencies(territory, today, tender=True, non_tender=False)
    if codes:
        by_territory[territory] = codes[0]

codes = sorted(set(by_territory.values()))
lines = [
    "// Generated by tool/currencies.py from Unicode CLDR (Babel). Do not edit.",
    "",
    "/// Every currency in use: ISO 4217 code to English name and minor digits.",
    "const currencyCatalogue = <String, ({String name, int digits})>{",
]
for code in codes:
    name = get_currency_name(code, locale="en").replace("'", "\\'")
    lines.append(f"  '{code}': (name: '{name}', digits: {get_currency_precision(code)}),")
lines += [
    "};",
    "",
    "/// Each territory's (ISO 3166 region's) currency.",
    "const territoryCurrencies = <String, String>{",
]
for territory, code in by_territory.items():
    lines.append(f"  '{territory}': '{code}',")
lines += ["};", ""]

out = pathlib.Path(__file__).resolve().parent.parent / "lib/src/core/money/currency_data.dart"
out.write_text("\n".join(lines))
print(f"{len(codes)} currencies, {len(by_territory)} territories -> {out}")
