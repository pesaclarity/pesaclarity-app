import 'package:crypto/crypto.dart';

/// Four words both phones show, so two people can check, face to face or on
/// a call, that the key they share is the same and nobody is in the middle
/// (decision 0031). Worked out from the space and both members' public
/// keys, so either side gets the same words.
List<String> safetyWords({
  required String spaceShareId,
  required List<int> keyA,
  required List<int> keyB,
}) {
  final a = keyA.toString();
  final b = keyB.toString();
  final (first, second) = a.compareTo(b) <= 0 ? (keyA, keyB) : (keyB, keyA);
  final digest = sha256.convert([
    ...'pcshare safety words v1|$spaceShareId|'.codeUnits,
    ...first,
    ...second,
  ]).bytes;
  return [for (var i = 0; i < 4; i++) _words[digest[i]]];
}

/// The words as the screens show them: `mango · river · seven · kettle`.
String safetyLine(List<String> words) => words.join(' \u00b7 ');

